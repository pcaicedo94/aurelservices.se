/**
 * Builds the logo the transactional mails carry, from the one source of truth
 * the site already uses (public/images/logo-white.png — the green wordmark).
 *
 * It writes two derived files, one per backend, because neither can reach the
 * other's:
 *   php/assets/logo-email.png   read from disk by php/lib/Mailer.php
 *   utils/emailLogo.js          the same bytes as base64, for the Node mailer,
 *                               which runs where public/ may not be shipped
 *
 *   node scripts/build-email-logo.mjs
 *
 * Run it again whenever the logo changes; nothing else reads these files.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "public/images/logo-white.png");
const png = path.join(root, "php/assets/logo-email.png");
const module = path.join(root, "utils/emailLogo.js");

// 400 px wide, shown at 200: sharp on a retina screen, still a few kilobytes.
// Flattened on white because the header band it sits on is white, and a client
// that paints transparency black would otherwise swallow the green wordmark.
const WIDTH = 400;

fs.mkdirSync(path.dirname(png), { recursive: true });
const info = await sharp(source)
  .resize({ width: WIDTH })
  .flatten({ background: "#ffffff" })
  .png({ compressionLevel: 9, palette: true })
  .toFile(png);

const base64 = fs.readFileSync(png).toString("base64");

const banner = `// The company logo for the transactional mails, as bytes rather than a URL.
//
// Why embedded: a remote <img> would have to point at the live site, which is
// still the old one and is moving to Simply — a broken logo inside a booking
// confirmation is worse than no logo. Reading the PNG from disk is no better,
// since a serverless function does not necessarily ship public/. So the bytes
// travel with the code and the mail carries them as an inline attachment.
//
// GENERATED by scripts/build-email-logo.mjs from public/images/logo-white.png.
// Do not edit by hand; run the script again instead.

export const LOGO_CID = "aurel-logo";

export const LOGO_WIDTH = ${Math.round(info.width / 2)};

const LOGO_PNG_BASE64 =
  "${base64}";

/** The nodemailer attachment the HTML's cid: reference resolves to. */
export function logoAttachment() {
  return {
    filename: "aurel-logo.png",
    content: Buffer.from(LOGO_PNG_BASE64, "base64"),
    contentType: "image/png",
    cid: LOGO_CID,
    contentDisposition: "inline",
  };
}
`;

fs.writeFileSync(module, banner);

const kb = (n) => `${Math.round(n / 1024)} KB`;
console.log(`php/assets/logo-email.png  ${info.width}x${info.height}  ${kb(info.size)}`);
console.log(`utils/emailLogo.js         ${kb(Buffer.byteLength(banner))}`);
